/**
 * Verbalized Sampling（確率つき複数案）の共通指示
 *
 * 複数案を出させるとき、各案に「その案を選ぶ確率」を添えさせると出力の多様性が上がる
 * ことが知られている。学習済みモデルは人が見慣れた無難な案に寄る傾向があり（典型性バイアス）、
 * 確率を明示させることで低確率＝大胆な案も同時に出せるようになる。
 *
 * probability は実際の確率ではなくモデルの主観的な「無難さ」の目安なので、UIでは数値を出さず
 * 「本命／意外」のような相対的なラベルとして扱う。
 */

/** 案の配列がひとつだけのプロンプト向け（クイック編集など） */
export const VS_INSTRUCTION = `- 各案には probability（あなたが通常その案を選ぶ確率。0.0〜1.0の数値）を添える
- 少なくとも1案は probability 0.15 未満の、意外性のある大胆な案にする`;

/**
 * 創造ポイント向け。ポイントと別案の2階層があるため、確率をどちらに付けるかを明示する。
 * 受信側（normalizeCreativePointsList）は別案の probability しか読まないので、
 * ポイント側に付けられると確率が黙って失われる。
 */
export const VS_INSTRUCTION_ALTERNATIVES = `- 各別案には probability（あなたが通常その別案を選ぶ確率。0.0〜1.0の数値）を添える（ポイント側には付けない）
- 各ポイントで少なくとも1つの別案は probability 0.15 未満の、意外性のある大胆な案にする`;
